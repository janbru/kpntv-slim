#!/usr/bin/env python3
"""Generates the app artwork: launcher icon (adaptive vectors + PNG fallbacks) and the TV banner.

Run from android/:  python3 art/make_art.py
Needs rsvg-convert (brew install librsvg). Fonts: Inter (banner wordmark).
Outputs go straight into app/src/main/res and art/preview.png.
"""
import math
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
ART = ROOT / "art"

GREEN = "#00C300"
GREEN_LIGHT = "#6BF07A"
BG_CENTER = "#16431F"
BG_EDGE = "#040B06"

# ---- the mark, in a 100x100 box: a rounded play triangle and two broadcast arcs ----
TRI = [(22, 24), (22, 76), (62, 50)]
ARC_CENTER = (54, 50)
ARCS = [(24, 1.0), (38, 0.55)]  # (radius, opacity)
ARC_SPAN = 40  # degrees above and below the horizontal
STROKE_TRI = 7
STROKE_ARC = 6
MARK_CENTER = (57, 50)  # visual centre of triangle + arcs


def arc_path(r, tx, ty, s):
    cx, cy = ARC_CENTER
    a = math.radians(ARC_SPAN)
    x1, y1 = cx + r * math.cos(-a), cy + r * math.sin(-a)
    x2, y2 = cx + r * math.cos(a), cy + r * math.sin(a)
    f = lambda x, y: (tx + (x - MARK_CENTER[0]) * s, ty + (y - MARK_CENTER[1]) * s)
    (X1, Y1), (X2, Y2) = f(x1, y1), f(x2, y2)
    return f"M{X1:.2f},{Y1:.2f} A{r * s:.2f},{r * s:.2f} 0 0 1 {X2:.2f},{Y2:.2f}"


def tri_path(tx, ty, s):
    pts = [(tx + (x - MARK_CENTER[0]) * s, ty + (y - MARK_CENTER[1]) * s) for x, y in TRI]
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + " Z"


def mark_svg(tx, ty, s, gid="g"):
    """SVG group for the mark centred at (tx, ty) and scaled by s."""
    out = [f'<g stroke-linecap="round" stroke-linejoin="round">']
    out.append(f'<path d="{tri_path(tx, ty, s)}" fill="url(#{gid})" stroke="url(#{gid})" stroke-width="{STROKE_TRI * s:.2f}"/>')
    for r, op in ARCS:
        out.append(f'<path d="{arc_path(r, tx, ty, s)}" fill="none" stroke="{GREEN}" stroke-opacity="{op}" stroke-width="{STROKE_ARC * s:.2f}"/>')
    out.append("</g>")
    return "\n".join(out)


def defs(gid="g", bg="bg", w=108, h=108):
    return f'''<defs>
<linearGradient id="{gid}" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{GREEN_LIGHT}"/><stop offset="1" stop-color="{GREEN}"/></linearGradient>
<radialGradient id="{bg}" gradientUnits="userSpaceOnUse" cx="{w * 0.5}" cy="{h * 0.5}" r="{max(w, h) * 0.62}"><stop offset="0" stop-color="{BG_CENTER}"/><stop offset="1" stop-color="{BG_EDGE}"/></radialGradient>
</defs>'''


# ---- Android adaptive icon (108dp canvas, ~66dp safe zone) ----
SCALE_ICON = 0.82


def write_adaptive():
    fg = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by art/make_art.py: play triangle + broadcast arcs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:pathData="{tri_path(54, 54, SCALE_ICON)}"
        android:strokeWidth="{STROKE_TRI * SCALE_ICON:.2f}"
        android:strokeLineJoin="round">
        <aapt:attr name="android:fillColor">
            <gradient android:startX="30" android:startY="30" android:endX="78" android:endY="78">
                <item android:color="{GREEN_LIGHT}" android:offset="0" />
                <item android:color="{GREEN}" android:offset="1" />
            </gradient>
        </aapt:attr>
        <aapt:attr name="android:strokeColor">
            <gradient android:startX="30" android:startY="30" android:endX="78" android:endY="78">
                <item android:color="{GREEN_LIGHT}" android:offset="0" />
                <item android:color="{GREEN}" android:offset="1" />
            </gradient>
        </aapt:attr>
    </path>
'''
    for r, op in ARCS:
        fg += f'''    <path
        android:pathData="{arc_path(r, 54, 54, SCALE_ICON)}"
        android:strokeColor="{GREEN}"
        android:strokeAlpha="{op}"
        android:strokeWidth="{STROKE_ARC * SCALE_ICON:.2f}"
        android:strokeLineCap="round" />
'''
    fg += "</vector>\n"
    (RES / "drawable/ic_foreground.xml").write_text(fg)

    bg = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by art/make_art.py: deep green glow. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="54" android:centerY="54" android:gradientRadius="67">
                <item android:color="{BG_CENTER}" android:offset="0" />
                <item android:color="{BG_EDGE}" android:offset="1" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
'''
    (RES / "drawable/ic_background.xml").write_text(bg)

    adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_background" />
    <foreground android:drawable="@drawable/ic_foreground" />
</adaptive-icon>
'''
    d = RES / "mipmap-anydpi-v26"
    (d / "ic_launcher.xml").write_text(adaptive)
    (d / "ic_launcher_round.xml").write_text(adaptive)


# ---- PNG fallbacks of the icon (legacy launchers, toast/system UI that cannot draw adaptive icons) ----
def icon_svg(size):
    s = 108
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108">
{defs("g", "bg", 108, 108)}
<rect width="108" height="108" fill="url(#bg)"/>
{mark_svg(54, 54, SCALE_ICON)}
</svg>'''


def icon_round_svg(size):
    return icon_svg(size).replace('<rect width="108" height="108" fill="url(#bg)"/>',
                                  '<circle cx="54" cy="54" r="54" fill="url(#bg)"/>')


def render(svg_text, out, w, h):
    tmp = ART / "_tmp.svg"
    tmp.write_text(svg_text)
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["rsvg-convert", "-w", str(w), "-h", str(h), "-o", str(out), str(tmp)], check=True)
    tmp.unlink()


def write_hint_icon():
    """Round icon for the in-app hint pill (30dp = 60px at xhdpi)."""
    render(icon_round_svg(60), RES / "drawable-xhdpi/hint_icon.png", 60, 60)


def write_icon_pngs():
    for name, px in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)]:
        render(icon_svg(px), RES / f"mipmap-{name}/ic_launcher.png", px, px)
        render(icon_round_svg(px), RES / f"mipmap-{name}/ic_launcher_round.png", px, px)


# ---- TV banner: 320x180dp, drawn at xhdpi (640x360 px) ----
def banner_svg():
    W, H = 640, 360
    rings = "".join(
        f'<circle cx="158" cy="180" r="{r}" fill="none" stroke="{GREEN}" stroke-opacity="{op}" stroke-width="2"/>'
        for r, op in [(150, 0.16), (215, 0.10), (285, 0.06), (360, 0.035)]
    )
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">
{defs("g", "bg", W, H)}
<rect width="{W}" height="{H}" fill="url(#bg)"/>
{rings}
{mark_svg(158, 180, 2.9)}
<text x="296" y="204" font-family="Inter, Roboto, Helvetica, Arial" font-size="72" letter-spacing="-1.5">
<tspan font-weight="800" fill="#FFFFFF">KPN</tspan><tspan font-weight="300" fill="{GREEN_LIGHT}" dx="16">Slim</tspan></text>
<text x="301" y="250" font-family="Inter, Roboto, Helvetica, Arial" font-size="24" font-weight="600" letter-spacing="8" fill="#FFFFFF" fill-opacity="0.55">LIVE TV</text>
</svg>'''


def write_banner():
    render(banner_svg(), RES / "drawable-xhdpi/banner.png", 640, 360)
    old = RES / "drawable/banner.xml"
    if old.exists():
        old.unlink()


def write_preview():
    tmp = ART / "_icon.png"
    render(icon_svg(256), tmp, 256, 256)
    subprocess.run(
        ["magick", str(RES / "drawable-xhdpi/banner.png"), "(", str(tmp), "-resize", "360x360", ")",
         "-background", "#222", "-gravity", "center", "+append", str(ART / "preview.png")],
        check=True)
    tmp.unlink()


if __name__ == "__main__":
    write_adaptive()
    write_icon_pngs()
    write_hint_icon()
    write_banner()
    write_preview()
    print("ok")
